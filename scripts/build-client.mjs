/**
 * RU: Финальная сборка браузерного бандла. Vite уже отдал IIFE с встроенным
 *     через `?inline` CSS; скрипт проверяет контракт DSH и пишет `dist/client.js`.
 * EN: Final browser bundle assembly. Vite already emitted an IIFE with the CSS
 *     inlined through `?inline`; this script verifies the DSH contract and writes
 *     `dist/client.js`.
 *
 * RU: Сборка падает, если нарушен контракт:
 *     - в бандле есть import/export или нет вызова __ModuleLoader__;
 *     - CSS не встроен (нет класса gv-card);
 *     - остались обращения к process.env (в браузере process отсутствует);
 *     - файл больше 1.5 МБ.
 * EN: The build fails when the contract is broken:
 *     - import/export is present or __ModuleLoader__ is missing;
 *     - CSS was not inlined (no gv-card class);
 *     - process.env references remain (browsers have no process);
 *     - the file exceeds 1.5 MB.
 */
import { readFile, writeFile, rm, mkdir } from 'node:fs/promises'
import { createHash } from 'node:crypto'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const rawPath = join(root, 'dist/vite-client/client.raw.js')
const outPath = join(root, 'dist/client.js')
const metaPath = join(root, 'dist/client.meta.json')
const MAX_BYTES = 1_500_000

function fail(message) {
  console.error(`[genvideo:build-client] ${message}`)
  process.exit(1)
}

const raw = await readFile(rawPath, 'utf8').catch(() => fail(`missing ${rawPath}; run vite build first`))

if (/^\s*(?:import|export)\s/m.test(raw)) fail('compiled client contains module syntax')
if (!raw.startsWith('(function()')) fail('vite output is not an IIFE')
if (!raw.includes('__ModuleLoader__')) fail('vite output lost the DSH module loader call')
if (!raw.includes('gv-card{')) fail('CSS was not inlined into the bundle')
if (raw.includes('process.env')) fail('process.env leaked into the browser bundle')

const banner = `/* GenVideo client bundle. Generated by scripts/build-client.mjs — do not edit. */\n`
const body = `${banner}${raw}\n`
if (Buffer.byteLength(body) > MAX_BYTES) fail(`bundle is ${Buffer.byteLength(body)} bytes (limit ${MAX_BYTES})`)

await mkdir(dirname(outPath), { recursive: true })
await writeFile(outPath, body, 'utf8')
await rm(join(root, 'dist/vite-client'), { recursive: true, force: true })

const hash = createHash('sha256').update(body).digest('hex').slice(0, 16)
const meta = {
  bytes: Buffer.byteLength(body),
  jsBytes: Buffer.byteLength(raw),
  hash,
  builtAt: new Date().toISOString(),
}
await writeFile(metaPath, `${JSON.stringify(meta, null, 2)}\n`, 'utf8')
console.log(`[genvideo:build-client] dist/client.js ${meta.bytes} bytes (${hash})`)
